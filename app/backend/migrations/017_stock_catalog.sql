-- Ориентир цены задаёт HEAD (правится в приложении), потолок = ориентир + допуск из «Значений» (stock.price_tolerance_pct).
-- Покупка в пределах потолка принимается сама, выше потолка или без ориентира — ждёт HEAD. Лимитов на месяц нет.

CREATE TABLE stock_depts (
    code     text PRIMARY KEY,
    title    text NOT NULL,
    category text NOT NULL REFERENCES expense_categories(code),   -- куда идут деньги в финансах (статья stock / canvas)
    sort     int  NOT NULL
);

CREATE TABLE stock_items (
    code       text PRIMARY KEY,               -- ХУД-001 и т.п., как в журнале
    dept       text NOT NULL REFERENCES stock_depts(code),
    section    text,
    name       text NOT NULL,
    unit       text,
    ref_price  numeric(12,2),                  -- ориентир за единицу, ₸ (NULL — ещё нет)
    where_buy  text,
    norm       text,                           -- норма склада (задел под остатки)
    sort       int  NOT NULL DEFAULT 0,
    active     boolean NOT NULL DEFAULT true,
    updated_by bigint REFERENCES people(id),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Строки чека: что купили, сколько, за сколько. Сумма строк = сумма траты в expenses.
CREATE TABLE stock_lines (
    id         bigserial PRIMARY KEY,
    expense_id bigint NOT NULL REFERENCES expenses(id),
    item_code  text REFERENCES stock_items(code),
    name       text NOT NULL,
    unit       text,
    qty        numeric(12,2) NOT NULL CHECK (qty > 0),
    amount     numeric(14,2) NOT NULL CHECK (amount > 0),
    ref_price  numeric(12,2),                  -- ориентир и потолок на момент покупки
    cap_price  numeric(12,2),
    flag       text NOT NULL CHECK (flag IN ('ok','above_ref','over_cap','no_ref'))
);
CREATE INDEX stock_lines_expense ON stock_lines (expense_id);
CREATE INDEX stock_lines_item ON stock_lines (item_code);

