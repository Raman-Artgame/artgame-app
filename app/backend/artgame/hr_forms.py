# Кандидат ступень не выбирает: старт у всех с первой ступени. Баллы — подсказка HEAD, с кем идти на экзамен быстрее.
YEARS = {"До 1 года": 1, "1–3 года": 2, "3–5 лет": 3, "Больше 5 лет": 4}
M2 = {"5–10 м²": 1, "10–20 м²": 2, "Больше 20 м²": 3}
NO = re.compile(r"^\s*(нет|не\b|никогда|жоқ|-)", re.I)
ART_STEPS = ((0, "support"), (5, "artist"), (9, "lead_artist"), (13, "artist_pro"))


def _said(v) -> bool:
    return isinstance(v, str) and len(v.strip()) >= 3 and not NO.match(v)


def level_hint(d: str, a: dict, photos: int) -> dict | None:
    if d == "art":
        why, n = [], 0
        y = YEARS.get(a.get("years"), 0)
        if y:
            n += y; why.append(a["years"])
        m = M2.get(a.get("m2"), 0)
        if m:
            n += m; why.append(a["m2"] + " за смену")
        if _said(a.get("lead")):
            n += 2; why.append("руководил людьми")
        for k, t in (("big", "крупный объект"), ("edu", "образование")):
            if _said(a.get(k)):
                n += 1; why.append(t)
        if set(a.get("transfer") or []) & {"Проектор", "Сетка"}:
            n += 1; why.append("проектор / сетка")
        if set(a.get("height") or []) & {"Леса", "Вышка или люлька", "Промальп"}:
            n += 1; why.append("высота")
        if a.get("kit") == "Есть":
            n += 1; why.append("свой инструмент")
        if len(a.get("tools") or []) >= 3:
            n += 1; why.append("3+ инструмента")
        if photos >= 3:
            n += 1; why.append(f"{photos} фото работ")
        code = [c for lo, c in ART_STEPS if n >= lo][-1]
        return {"code": code, "score": n, "max": 16, "why": why}
    if d == "print":
        why, n = [], 0
        if _said(a.get("printers")):
            n += 3; why.append("работал с принтерами")
