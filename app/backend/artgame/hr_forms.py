def keys(form: dict) -> dict:
    """Ключ вопроса → описание: по нему сервер чистит ответы анкеты, открытой без входа."""
    out = {}
    for s in form["steps"]:
        for it in s["items"]:
            out[it["key"]] = it
    return out


