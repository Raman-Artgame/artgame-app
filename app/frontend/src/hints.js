export function hintsFor(step, role, cond = {}, v = {}) {
  const g = GROUP[role] || 'artist'
  return ITEMS[step].filter(([, who, when, roleOk]) => (!who || who.includes(g)) && (!when || when(cond)) && (!roleOk || roleOk(role)))
    .map(([t]) => (typeof t === 'function' ? t(v) : t))
}

